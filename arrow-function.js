// ==========================================
// Arrow Function (ES6)
// ==========================================

// Arrow Functions use the => operator.

// They are shorter than normal functions.

// Syntax

// const functionName = (parameters) => {

// };

// Example

const square = (n) => n * n;

console.log(square(4));

// Output

// 16

// Explanation

// n is the parameter.

// square(4)

// n becomes 4

// returns

// 4 × 4

// = 16
