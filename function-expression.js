// ==========================================
// Function Expression
// ==========================================

// A Function Expression is a function
// assigned to a variable.

// It can be named or anonymous.

// Syntax

// const variableName = function(){

// };

// Example

const add = function (a, b) {

    return a + b;

};

console.log(add(2, 3));

// Output

// 5

// Explanation

// add stores the function.

// Calling add(2,3) executes the function.

// return sends the answer back.