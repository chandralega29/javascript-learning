// ==========================================
// Named Function
// ==========================================

// A Named Function is a function that has its own name.

// It can be called using its function name.

// Named functions are easy to reuse and debug.

// Syntax

// function functionName() {

// }

// Example

function greet() {

    return "Hello!";

}

console.log(greet());

// Output

// Hello!

// Explanation

// greet() is the function name.

// return sends the value back.

// console.log() prints the returned value.