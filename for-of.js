// ==========================================
// for...of Loop
// ==========================================

// for...of gives values.
// You get the actual values.

// Used to loop through values of iterable things like:

// Arrays
// Strings
// Maps
// Sets

const fruits = ["apple", "banana", "mango"];

for (const one of fruits) {

  console.log(one);

}

/*
Output:

apple
banana
mango
*/